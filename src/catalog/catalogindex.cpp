QVector<TextureRecord> CatalogIndex::allRecords() const
{
    QVector<TextureRecord> records;

    QSqlQuery query = const_cast<Database&>(db).prepare(
        QStringLiteral("SELECT %1 FROM texture").arg(QLatin1String(kColumns)));
    if (!query.exec())
        return records;

    while (query.next())
        records.append(readRow(query));

    return records;
}

bool CatalogIndex::markMissing(qint64 id, qint64 whenMs)
{
    if (readOnly) {
        db.setError(QStringLiteral("index is read-only"));
        return false;
    }

    // Only stamp the first time, so the dimmed card can say how long it's been
    // gone rather than resetting on every launcher open.
    QSqlQuery query = db.prepare(QStringLiteral(
        "UPDATE texture SET missing_since = ? WHERE id = ? AND missing_since IS NULL"));
    query.addBindValue(whenMs);
    query.addBindValue(id);
    if (!query.exec()) {
        db.setError(query.lastError().text());
        return false;
    }
    return true;
}

bool CatalogIndex::markPresent(qint64 id, qint64 fileSize, qint64 fileMtime)
{
    if (readOnly) {
        db.setError(QStringLiteral("index is read-only"));
        return false;
    }

    QSqlQuery query = db.prepare(QStringLiteral(
        "UPDATE texture SET missing_since = NULL, file_size = ?, file_mtime = ? WHERE id = ?"));
    query.addBindValue(fileSize);
    query.addBindValue(fileMtime);
    query.addBindValue(id);
    if (!query.exec()) {
        db.setError(query.lastError().text());
        return false;
    }
    return true;
}

qint64 CatalogIndex::relocate(qint64 id, const QString& newPath, qint64 fileSize,
                              qint64 fileMtime)
{
    if (readOnly) {
        db.setError(QStringLiteral("index is read-only"));
        return -1;
    }
    if (newPath.isEmpty())
        return -1;

    const TextureRecord moving = byId(id);
    if (!moving.isValid())
        return -1;

    Transaction tx(db);
    if (!tx.isActive())
        return -1;

    const TextureRecord existing = byPath(newPath);

    // Already indexed under the new path — usually because the user opened it
    // there before getting round to fixing the stale card. Fold the old row's
    // user data into it rather than failing on the UNIQUE constraint.
    if (existing.isValid() && existing.id != id) {
        QSqlQuery merge = db.prepare(QStringLiteral(
            "UPDATE texture SET "
            "  starred     = max(starred, ?), "
            "  created_at  = min(created_at, ?), "
            "  last_opened = max(coalesce(last_opened, 0), ?), "
            "  last_saved  = max(coalesce(last_saved, 0), ?), "
            "  missing_since = NULL "
            "WHERE id = ?"));
        merge.addBindValue(moving.starred ? 1 : 0);
        merge.addBindValue(moving.createdAt != 0 ? moving.createdAt : existing.createdAt);
        merge.addBindValue(moving.lastOpened);
        merge.addBindValue(moving.lastSaved);
        merge.addBindValue(existing.id);
        if (!merge.exec()) {
            db.setError(merge.lastError().text());
            return -1;
        }

        QSqlQuery moveTags = db.prepare(
            QStringLiteral("INSERT OR IGNORE INTO tag (texture_id, tag) "
                           "SELECT ?, tag FROM tag WHERE texture_id = ?"));
        moveTags.addBindValue(existing.id);
        moveTags.addBindValue(id);
        if (!moveTags.exec()) {
            db.setError(moveTags.lastError().text());
            return -1;
        }

        QSqlQuery drop = db.prepare(QStringLiteral("DELETE FROM texture WHERE id = ?"));
        drop.addBindValue(id);
        if (!drop.exec()) {
            db.setError(drop.lastError().text());
            return -1;
        }

        return tx.commit() ? existing.id : -1;
    }

    QSqlQuery query = db.prepare(QStringLiteral(
        "UPDATE texture SET path = ?, name = ?, file_size = ?, file_mtime = ?, "
        "missing_since = NULL WHERE id = ?"));
    query.addBindValue(newPath);
    query.addBindValue(QFileInfo(newPath).completeBaseName());
    query.addBindValue(fileSize);
    query.addBindValue(fileMtime);
    query.addBindValue(id);

    if (!query.exec()) {
        db.setError(query.lastError().text());
        return -1;
    }

    return tx.commit() ? id : -1;
}

