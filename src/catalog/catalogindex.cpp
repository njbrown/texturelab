QStringList CatalogIndex::tags(qint64 id) const
{
    QStringList result;

    QSqlQuery query = const_cast<Database&>(db).prepare(
        QStringLiteral("SELECT tag FROM tag WHERE texture_id = ? ORDER BY tag"));
    query.addBindValue(id);

    if (!query.exec())
        return result;

    while (query.next())
        result << query.value(0).toString();

    return result;
}

bool CatalogIndex::addTag(qint64 id, const QString& tag)
{
    if (readOnly || tag.isEmpty()) {
        db.setError(QStringLiteral("index is read-only or tag is empty"));
        return false;
    }

    QSqlQuery query = db.prepare(
        QStringLiteral("INSERT OR IGNORE INTO tag (texture_id, tag) VALUES (?, ?)"));
    query.addBindValue(id);
    query.addBindValue(tag);
    if (!query.exec()) {
        db.setError(query.lastError().text());
        return false;
    }
    return true;
}

bool CatalogIndex::removeTag(qint64 id, const QString& tag)
{
    if (readOnly) {
        db.setError(QStringLiteral("index is read-only"));
        return false;
    }

    QSqlQuery query = db.prepare(
        QStringLiteral("DELETE FROM tag WHERE texture_id = ? AND tag = ?"));
    query.addBindValue(id);
    query.addBindValue(tag);
    if (!query.exec()) {
        db.setError(query.lastError().text());
        return false;
    }
    return query.numRowsAffected() > 0;
}

