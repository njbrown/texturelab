QString CatalogIndex::whereClause(const Query& query)
{
    QStringList clauses;

    switch (query.filter) {
    case Filter::All:
        break;
    case Filter::Recents:
        // Matches the ix_recent partial index. Recents is "jump back in", so a
        // file that isn't there isn't useful; All and Starred still show it.
        clauses << QStringLiteral("last_opened IS NOT NULL")
                << QStringLiteral("missing_since IS NULL");
        break;
    case Filter::Starred:
        clauses << QStringLiteral("starred = 1");
        break;
    }

    if (!query.search.isEmpty()) {
        clauses << QStringLiteral(
            R"((name LIKE :search ESCAPE '\' OR EXISTS (
                   SELECT 1 FROM tag WHERE tag.texture_id = texture.id
                   AND tag.tag LIKE :search ESCAPE '\')))");
    }

    if (clauses.isEmpty())
        return QString();

    return QStringLiteral(" WHERE ") + clauses.join(QStringLiteral(" AND "));
}

QString CatalogIndex::orderByClause(const Query& query)
{
    const QString direction = query.ascending ? QStringLiteral("ASC") : QStringLiteral("DESC");

    switch (query.sort) {
    case SortKey::Name:
        return QStringLiteral(" ORDER BY name COLLATE NOCASE %1, id %1").arg(direction);
    case SortKey::Size:
        return QStringLiteral(" ORDER BY file_size %1, id %1").arg(direction);
    case SortKey::Opened:
        // Spelled out rather than using NULLS LAST so the ordering doesn't
        // depend on which SQLite version Qt happens to bundle. Never-opened
        // rows sort last either way.
        return QStringLiteral(" ORDER BY (last_opened IS NULL) ASC, last_opened %1, id %1")
            .arg(direction);
    case SortKey::Modified:
        break;
    }
    return QStringLiteral(" ORDER BY file_mtime %1, id %1").arg(direction);
}

QVector<TextureRecord> CatalogIndex::list(const Query& query) const
{
    QVector<TextureRecord> records;

    QString sql = QStringLiteral("SELECT %1 FROM texture").arg(QLatin1String(kColumns));
    sql += whereClause(query);
    sql += orderByClause(query);

    if (query.limit >= 0)
        sql += QStringLiteral(" LIMIT :limit OFFSET :offset");

    QSqlQuery q = const_cast<Database&>(db).prepare(sql);
    if (!query.search.isEmpty())
        q.bindValue(QStringLiteral(":search"),
                    QStringLiteral("%%%1%%").arg(escapeLike(query.search)));
    if (query.limit >= 0) {
        q.bindValue(QStringLiteral(":limit"), query.limit);
        q.bindValue(QStringLiteral(":offset"), query.offset);
    }

    if (!q.exec()) {
        const_cast<Database&>(db).setError(q.lastError().text());
        qWarning("catalog: list failed: %s", qPrintable(q.lastError().text()));
        return records;
    }

    while (q.next())
        records.append(readRow(q));

    return records;
}

int CatalogIndex::count(const Query& query) const
{
    QString sql = QStringLiteral("SELECT count(*) FROM texture");
    sql += whereClause(query);

    QSqlQuery q = const_cast<Database&>(db).prepare(sql);
    if (!query.search.isEmpty())
        q.bindValue(QStringLiteral(":search"),
                    QStringLiteral("%%%1%%").arg(escapeLike(query.search)));

    if (!q.exec() || !q.next())
        return 0;

    return q.value(0).toInt();
}

TextureRecord CatalogIndex::readRow(const QSqlQuery& query)
{
    TextureRecord rec;
    rec.id = query.value(0).toLongLong();
    rec.path = query.value(1).toString();
    rec.name = query.value(2).toString();
    rec.fileSize = query.value(3).toLongLong();
    rec.fileMtime = query.value(4).toLongLong();
    rec.width = query.value(5).toInt();
    rec.height = query.value(6).toInt();
    rec.nodeCount = query.value(7).toInt();
    rec.libVersion = query.value(8).toString();
    rec.channels = query.value(9).toInt();
    rec.createdAt = query.value(10).toLongLong();
    rec.lastOpened = query.value(11).isNull() ? 0 : query.value(11).toLongLong();
    rec.lastSaved = query.value(12).isNull() ? 0 : query.value(12).toLongLong();
    rec.starred = query.value(13).toBool();
    rec.missingSince = query.value(14).isNull() ? 0 : query.value(14).toLongLong();
    return rec;
}

TextureRecord CatalogIndex::byId(qint64 id) const
{
    QSqlQuery query = const_cast<Database&>(db).prepare(
        QStringLiteral("SELECT %1 FROM texture WHERE id = ?").arg(QLatin1String(kColumns)));
    query.addBindValue(id);

    if (!query.exec() || !query.next())
        return TextureRecord();

    return readRow(query);
}

TextureRecord CatalogIndex::byPath(const QString& path) const
{
    QSqlQuery query = const_cast<Database&>(db).prepare(
        QStringLiteral("SELECT %1 FROM texture WHERE path = ?").arg(QLatin1String(kColumns)));
    query.addBindValue(path);

    if (!query.exec() || !query.next())
        return TextureRecord();

    return readRow(query);
}

